def known_issue_ids(root, skills):
    ids = set()
    for skill in skills:
        path = os.path.join(root, skill, "references", "known-issues.md")
        for line in ((read_text(path) if os.path.isfile(path) else None) or "").split("\n"):
            m = KNOWN_ISSUE_ROW_RE.match(line)
            if m:
                ids.add(m.group(1))
    return ids


def banned_allowed(family, match, known_issues):
    text = match.group(0)
    if family == "ticket key":
        return (text in TICKET_ALLOW or text in known_issues
                or any(re.fullmatch(p, text) for p in TICKET_ALLOW_PATTERNS))
    if family == "IP address":
        if any(int(o) > 255 for o in match.groups()) or text in ALLOWED_IPS:
            return True
        try:
            ip = ipaddress.ip_address(text)
        except ValueError:
            return False
        return any(ip in ipaddress.ip_network(net) for net in DOC_NETWORKS)
    if family == "UUID":
        return set(text.replace("-", "")) == {"0"} or text.lower() in ALLOWED_UUIDS
    if family == "email address":
        domain = match.group(1).lower()
        return text.lower() in ALLOWED_EMAILS or any(domain == d or domain.endswith("." + d) for d in ALLOWED_EMAIL_DOMAINS)
    if family == "internal hostname":
        return text.lower() in ALLOWED_AFFINIDI_HOSTS
    return False


def shown(family, text):
    if family == "secret":
        return "%s... (%d characters, redacted)" % (text[:6], len(text))
    return text if len(text) <= 60 else text[:57] + "..."


def check_banned(root, files, known_issues, report):
    scanned = 0
    for rel in files:
        if rel in BANNED_EXEMPT or rel.startswith(BANNED_EXEMPT_DIRS):
            continue
        for family, pattern in BANNED[:2]:
            m = pattern.search(rel)
            if m:
                report.add(rel, 1, "banned", "file name contains a %s: %s" % (family, shown(family, m.group(0))))
        text = read_text(os.path.join(root, rel))
        if text is None:
            continue
        scanned += 1
        for lineno, line in enumerate(text.split("\n"), start=1):
            for family, pattern in BANNED:
                for m in pattern.finditer(line):
                    if not banned_allowed(family, m, known_issues):
                        report.add(rel, lineno, "banned", "%s: %s" % (family, shown(family, m.group(0))))
    return scanned


