class Report:
    def __init__(self, root):
        self.root = root
        self.problems = []

    def add(self, path, line, check, message):
        if os.path.isabs(path):
            path = os.path.relpath(path, self.root)
        self.problems.append((path.replace(os.sep, "/"), int(line or 1), check, message))

    def print(self):
        for path, line, check, message in sorted(set(self.problems)):
            print("%s:%d: [%s] %s" % (path, line, check, message))


def list_files(root):
    """Tracked and untracked-but-not-ignored files, relative to root, '/'-separated."""
    try:
        proc = subprocess.run(["git", "-C", root, "ls-files", "-co", "--exclude-standard", "-z"],
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE)
        if proc.returncode == 0:
            names = [n for n in proc.stdout.decode("utf-8", "replace").split("\0") if n]
            return sorted(set(n for n in names if os.path.isfile(os.path.join(root, n))))
    except OSError:
        pass
    out = []
    for dirpath, dirnames, filenames in os.walk(root):
        dirnames[:] = sorted(d for d in dirnames if d not in WALK_SKIP_DIRS)
        out.extend(os.path.relpath(os.path.join(dirpath, n), root).replace(os.sep, "/")
                   for n in filenames if not n.endswith(".pyc"))
    return sorted(out)


def read_text(path):
    with open(path, "rb") as fh:
        data = fh.read()
    if b"\0" in data[:8192]:
        return None
    return data.decode("utf-8", "replace")


