def skill_dirs(files):
    return sorted(set("skills/" + f.split("/")[1] for f in files if f.startswith("skills/") and f.count("/") >= 2))


def check_skill(skill, docs, report):
    """Frontmatter presence and size; returns SKILL.md's metadata, or None without frontmatter."""
    rel = skill + "/SKILL.md"
    doc = docs.get(rel)
    if doc is None:
        report.add(skill, 1, "frontmatter", "skill directory has no SKILL.md")
        return None
    if doc.fields is None:
        report.add(rel, 1, "frontmatter", "SKILL.md must start with '---' frontmatter closed by '---'")
        return None
    for key in ("name", "description"):
        if not doc.fields.get(key, ("", 0))[0].strip():
            report.add(rel, doc.fields.get(key, ("", 1))[1], "frontmatter", "frontmatter needs a non-empty %r" % key)
    lines = len(doc.lines) - (doc.lines[-1] == "")
    if lines >= 500:
        report.add(rel, 500, "size", "SKILL.md has %d lines; keep it under 500 and move detail to references/" % lines)
    tokens = int(math.ceil(len("\n".join(doc.lines[doc.frontmatter_end:])) / 4.0))
    if tokens >= 5000:
        report.add(rel, doc.frontmatter_end + 1, "size", "SKILL.md body is about %d tokens (chars / 4); keep it under 5000" % tokens)
    return doc.metadata


def check_anchor(root, report, rel_file, lineno, target_abs, anchor, docs, target):
    rel_target = os.path.relpath(target_abs, root).replace(os.sep, "/")
    doc = docs.get(rel_target)
    if doc is None:
        text = read_text(target_abs)
        if text is None:
            return
        doc = docs[rel_target] = MdDoc(text)
    anchor = urllib.parse.unquote(anchor)
    if anchor not in doc.anchors():
        close = difflib.get_close_matches(anchor, sorted(doc.anchors()), n=3)
        report.add(rel_file, lineno, "links", "link %r: no heading with anchor #%s in %s%s"
                   % (target, anchor, rel_target, "; did you mean: " + ", ".join("#" + c for c in close) if close else ""))


def check_links(root, rel_file, doc, docs, skills, report):
    base = os.path.dirname(os.path.join(root, rel_file))
    skill = next((s for s in skills if rel_file.startswith(s + "/")), None)
    for fence in doc.fences:
        if not fence.closed:
            report.add(rel_file, fence.line, "markdown", "code fence opened here is never closed")
    for lineno, target in links_in(doc):
        if target.startswith("<") and target.endswith(">"):
            target = target[1:-1]
        if not target:
            report.add(rel_file, lineno, "links", "empty link target")
            continue
        if re.match(r"^[A-Za-z][A-Za-z0-9+.-]*:", target):
            continue
        if target.startswith("/"):
            report.add(rel_file, lineno, "links", "link %r is absolute; use a path relative to this file" % target)
            continue
        path_part, _, anchor = target.partition("#")
        path_part = urllib.parse.unquote(path_part.split("?", 1)[0])
        resolved = os.path.normpath(os.path.join(base, path_part)) if path_part else os.path.join(root, rel_file)
        if os.path.relpath(resolved, root).replace(os.sep, "/").startswith("../"):
            report.add(rel_file, lineno, "links", "link %r points outside the repository" % target)
            continue
        if skill is not None:
            inside = os.path.relpath(resolved, os.path.join(root, skill)).replace(os.sep, "/")
            if inside == ".." or inside.startswith("../"):
                report.add(rel_file, lineno, "references", "link %r leaves the skill directory" % target)
                continue
        if not os.path.exists(resolved):
            report.add(rel_file, lineno, "links", "broken link %r: %s does not exist"
                       % (target, os.path.relpath(resolved, root).replace(os.sep, "/")))
        elif anchor and resolved.endswith(".md") and os.path.isfile(resolved):
            check_anchor(root, report, rel_file, lineno, resolved, anchor, docs, target)


