#!/usr/bin/env python3
"""Offline checks specific to this repository; `make validate` runs them and CI runs `make ci`.

The standard validators cover the rest, in CI (.github/workflows/check.yml): `claude plugin
validate` checks the marketplace manifest (`.`) and the plugin manifest
(`.claude-plugin/plugin.json`), and with `--strict` that the skill's frontmatter parses and has a
description (`skills`), and `gh skill publish --dry-run` checks the Agent Skills name rules, that
the name equals the directory name, and that name and description are present.

Every problem is printed as `path:line: [check] message`, all of them, then a one-line summary.

  [frontmatter]  SKILL.md starts with '---' frontmatter that has a name and a description.
  [size]         SKILL.md is under 500 lines and its body under 5000 estimated tokens (chars / 4).
  [links]        Relative links in every Markdown file resolve, and their #anchors match a GitHub
                 heading slug.
  [references]   No link in a skill directory leaves it.
  [matrix]       .github/skill-drift-matrix.json has a 'baseline' object, an entry for every page the skill
                 ships (SKILL.md and the Markdown under references/) and none for a page it does not.
                 Whether a page's 'Sources:' line agrees with its entry is not checked.
  [banned]       No personal paths, test-only gateway hooks, internal hosts, IP literals, ticket keys,
                 UUIDs, secrets, private email addresses or tool attribution in any tracked file.
                 Attribution means authorship phrases (co-author trailers, "generated by" or "written
                 with" an assistant, "built at" or "made by" its vendor), assistant model ids and
                 assistants' noreply addresses; naming a vendor or a tool in prose is not attribution.
  [maintainer]   Files under skills/ (what users get) name no tests/ or scripts/ path and no commit id,
                 outside fenced code, except the public gateway commit in SKILL.md's
                 metadata.gateway_commit.
  [reviewed]     The reviewed gateway and fabric versions (SKILL.md metadata.gateway, metadata.fabric)
                 and dates in the metadata.checked month appear only in SKILL.md metadata, its one
                 'Reviewed against' line and commands.md's generated header; nowhere else under skills/
                 and not in the plugin descriptions. The 'Reviewed against' line agrees with metadata,
                 metadata.gateway_commit is the first 12 characters of the matrix baseline.agent_gateway,
                 and metadata.gateway and metadata.fabric equal the matrix baseline.gateway and
                 baseline.fabric.
  [fabric]       Every `fabric ...` command in the skill's Markdown exists in the CLI snapshot,
                 .github/fabric-cli-snapshot.json, with the options it names.
  [generated]    references/commands.md is exactly what gen-cli-reference.py renders from the snapshot.
  [markdown]     A code fence that is never closed.

Limits, accepted to keep the checks small:
  - "Tracked" means `git ls-files -co --exclude-standard`; outside a git work tree every file under
    --root is walked instead (skipping .git, __pycache__ and .e2e-work).
  - Frontmatter is read line by line: top-level `key: value` lines and `metadata` children indented
    two spaces, with one pair of surrounding quotes removed. Nothing checks the description's
    1024-character limit.
  - Headings are ATX (`#`) headings; setext headings and HTML anchors are not anchors here. Links are
    inline `[text](target)` links and images; reference definitions and URLs with a scheme are not
    checked. Inline code spans are read one line at a time.
  - The fabric scan reads fenced shell blocks (bash, sh, shell, console, zsh or untagged) and inline
    code starting with `fabric `. It joins backslash continuations, skips heredoc bodies, reads a
    quoted string that spans lines one line at a time, and treats `|`, `;`, `&`, `<`, `>`, `(`, `)`
    and backticks outside quotes as the end of a command. It checks the literal word `fabric` in
    command position only: at the start, after an operator, an assignment or a word such as `if` or
    `exec`; `$FABRIC`, `fab` and paths ending in /fabric are not checked. Quotes are removed from a
    word before it is read; a word starting with `$`, `<`, `[` or `{` or holding `...` is a
    placeholder and ends the subcommand path; `${...}` is one word. `$(...)` bodies are read as
    commands of their own, inside double quotes too; backticks inside double quotes are not, and
    arguments after a redirection are not read.
  - The banned-content patterns are assembled from pieces below so that this file itself does not
    contain them; this file, tests/unit/test_validate.py and tests/unit/fixtures/ are exempt.
"""

