DRIFT_MATRIX = ".github/skill-drift-matrix.json"


def json_line(text, needle, after=0):
    lines = text.split("\n")
    return next((i + 1 for i in range(after, len(lines)) if needle in lines[i]), 1)


def shipped_pages(skills, docs):
    """Each skill's SKILL.md and the Markdown pages under its references/."""
    return set(rel for rel in docs for skill in skills
               if rel == skill + "/SKILL.md" or (rel.startswith(skill + "/references/") and rel.endswith(".md")))


def check_matrix(root, docs, skills, report):
    """The drift matrix has a baseline and one entry per shipped page."""
    path = os.path.join(root, DRIFT_MATRIX)
    text = read_text(path) if os.path.isfile(path) else None
    try:
        data = json.loads(text or "")
        baseline, pages = data["baseline"], data["pages"]
        if not isinstance(baseline, dict) or not isinstance(pages, dict):
            raise TypeError
    except (ValueError, KeyError, TypeError):
        report.add(DRIFT_MATRIX, 1, "matrix", "missing or unreadable; expected an object with 'baseline' and 'pages'")
        return
    shipped = shipped_pages(skills, docs)
    for rel in sorted(shipped - set(pages)):
        report.add(DRIFT_MATRIX, json_line(text, '"pages"'), "matrix",
                   "no entry for %s, a page the skill ships; list the source paths and docs pages it relies on" % rel)
    for rel in sorted(set(pages) - shipped):
        report.add(DRIFT_MATRIX, json_line(text, '"%s"' % rel), "matrix",
                   "entry for %s, which is not a page the skill ships; rename or remove the entry with the page" % rel)


