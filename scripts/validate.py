def check_generated(root, tree, report):
    rel = "skills/" + MAIN_SKILL + "/" + COMMANDS_MD
    spec = importlib.util.spec_from_file_location("gen_cli_reference", os.path.join(SCRIPTS_DIR, "gen-cli-reference.py"))
    gen = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gen)
    path = os.path.join(root, rel)
    if not os.path.isfile(path):
        report.add(rel, 1, "generated", "missing; run make cli-reference")
        return
    text = read_text(path) or ""
    version = tree.get("fabric_version")
    m = gen.BANNER_RE.match(text.split("\n", 1)[0])
    if not m:
        report.add(rel, 1, "generated", "must start with the banner %r" % gen.BANNER.format(version=version))
    elif m.group("version") != version:
        report.add(rel, 1, "generated", "banner says fabric %s but %s records fabric %s" % (m.group("version"), CLI_SNAPSHOT, version))
    try:
        expected = gen.render_markdown(tree)
    except (KeyError, TypeError) as exc:
        report.add(CLI_SNAPSHOT, 1, "generated", "cannot render commands.md from it: %r" % exc)
        return
    if m and text != expected:
        old, new = text.split("\n"), expected.split("\n")
        line = next((k + 1 for k in range(min(len(old), len(new))) if old[k] != new[k]), min(len(old), len(new)))
        report.add(rel, line, "generated",
                   "does not match what gen-cli-reference.py renders from %s (edited by hand?); run make cli-reference" % CLI_SNAPSHOT)


