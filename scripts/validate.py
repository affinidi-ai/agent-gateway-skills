MAINTAINER_PATTERNS = (
    (re.compile(r"(?<![\w./-])(?:tests|scripts)/"),
     "names %r, a path in this repository's maintainer tree that users do not get; say what was checked "
     "in user terms instead, such as 'reproduced on a running gateway'"),
    (re.compile(r"(?<![0-9A-Za-z_])(?=[0-9a-f]*[a-f])(?=[0-9a-f]*[0-9])[0-9a-f]{9,}(?![0-9A-Za-z_])"),
     "%r looks like a commit id, which users cannot look up; say 'the reviewed version' or describe the change"),
)
MONTHS = ("January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
          "November", "December")
REVIEWED_LINE_RE = re.compile(
    r"^Reviewed against gateway (?P<gateway>\S+) and fabric (?P<fabric>\S+) \((?P<month>[A-Za-z]+) (?P<year>\d{4})\)\.$")
REVIEWED_LINE_SHAPE = "Reviewed against gateway <metadata.gateway> and fabric <metadata.fabric> (<Month YYYY>)."
NAMED_VERSION_RE = re.compile(r"(?i)\b(?:gateway|fabric)\s+v?\d+\.\d+\.\d+\b")


def check_maintainer_material(skill, docs, report):
    for rel, doc in sorted(docs.items()):
        if not rel.startswith(skill + "/"):
            continue
        # The gateway is public, so SKILL.md may name its reviewed commit in this one metadata key.
        commit_line = (doc.metadata or {}).get("gateway_commit", (None, 0))[1] if rel == skill + "/SKILL.md" else 0
        frontmatter = [(i + 1, doc.lines[i]) for i in range(1, max(doc.frontmatter_end - 1, 1))]
        for lineno, line in frontmatter + doc.prose:
            for pattern, message in MAINTAINER_PATTERNS:
                if lineno == commit_line and pattern is MAINTAINER_PATTERNS[1][0]:
                    continue
                for m in pattern.finditer(line):
                    report.add(rel, lineno, "maintainer", message % m.group(0))


def literal_matches(patterns, line):
    """(kind, text) for each pattern match in line, skipping matches inside an earlier, wider one."""
    found = sorted((m.start(), -m.end(), kind, m.group(0)) for kind, pattern in patterns for m in pattern.finditer(line))
    out, reach = [], -1
    for start, neg_end, kind, text in found:
        if start >= reach:
            out.append((kind, text))
            reach = -neg_end
    return out


def check_gateway_commit(root, rel_skill_md, metadata, report):
    """metadata.gateway_commit is the reviewed public gateway commit: the matrix baseline's first 12 characters."""
    commit, lineno = metadata.get("gateway_commit", (None, 0))
    if commit is None:
        if metadata.get("gateway"):
            report.add(rel_skill_md, 1, "reviewed", "no metadata.gateway_commit; set it to the first 12 characters "
                       "of baseline.agent_gateway in %s" % DRIFT_MATRIX)
        return
    if not re.match(r"^[0-9a-f]{12}$", commit):
        report.add(rel_skill_md, lineno, "reviewed", "metadata.gateway_commit %r is not 12 lowercase hex characters" % commit)
        return
    path = os.path.join(root, DRIFT_MATRIX)
    try:
        baseline = json.loads((read_text(path) if os.path.isfile(path) else None) or "")["baseline"]["agent_gateway"]
    except (ValueError, KeyError, TypeError):
        return  # the matrix rule reports a missing or unreadable matrix
    if not isinstance(baseline, str) or baseline[:12] != commit:
        report.add(rel_skill_md, lineno, "reviewed", "metadata.gateway_commit %s is not the start of baseline.agent_gateway "
                   "%s in %s" % (commit, baseline, DRIFT_MATRIX))


def check_baseline_versions(root, rel_skill_md, metadata, report):
    """metadata.gateway and metadata.fabric are the versions in the matrix baseline, which the upstream check reads."""
    path = os.path.join(root, DRIFT_MATRIX)
    try:
        baseline = json.loads((read_text(path) if os.path.isfile(path) else None) or "")["baseline"]
    except (ValueError, KeyError, TypeError):
        return  # the matrix rule reports a missing or unreadable matrix
    if not isinstance(baseline, dict):
        return
    for key in ("gateway", "fabric"):
        version, lineno = metadata.get(key, (None, 0))
        if version is not None and baseline.get(key) != version:
            report.add(rel_skill_md, lineno, "reviewed", "metadata.%s %s is not baseline.%s %s in %s; set both in "
                       "the same change" % (key, version, key, baseline.get(key), DRIFT_MATRIX))


def check_reviewed_literals(root, skill, metadata, files, docs, report):
    """Reviewed versions and review-month dates only where SKILL.md and commands.md allow them."""
    rel_skill_md = skill + "/SKILL.md"
    doc = docs[rel_skill_md]
    gateway = metadata.get("gateway", (None, 0))[0]
    fabric = metadata.get("fabric", (None, 0))[0]
    checked, checked_line = metadata.get("checked", (None, 0))
    check_gateway_commit(root, rel_skill_md, metadata, report)
    check_baseline_versions(root, rel_skill_md, metadata, report)
    patterns = [("version", NAMED_VERSION_RE)]
    patterns += [("version", re.compile(r"(?<![0-9A-Za-z.])v?" + re.escape(v) + r"(?![0-9A-Za-z]|\.[0-9])"))
                 for v in (gateway, fabric) if v]
    month = None
    if checked is not None:
        m = re.match(r"^(\d{4})-(\d{2})-(\d{2})$", checked)
        if not m or not 1 <= int(m.group(2)) <= 12:
            report.add(rel_skill_md, checked_line, "reviewed", "metadata.checked %r is not a YYYY-MM-DD date" % checked)
        else:
            month = (MONTHS[int(m.group(2)) - 1], m.group(1))
            patterns.append(("date", re.compile(r"(?<!\d)" + re.escape(checked[:7]) + r"-\d{2}(?!\d)")))

    allowed = {rel_skill_md: set(lineno for _, lineno in metadata.values())}
    reviewed = [(i, REVIEWED_LINE_RE.match(line)) for i, line in enumerate(doc.lines, start=1)
                if i > doc.frontmatter_end and line.startswith("Reviewed against")]
    for lineno, m in reviewed[:1]:
        allowed[rel_skill_md].add(lineno)
        if m is None:
            report.add(rel_skill_md, lineno, "reviewed", "the 'Reviewed against' line must read exactly: %s" % REVIEWED_LINE_SHAPE)
            continue
        for key, value in (("gateway", gateway), ("fabric", fabric)):
            if m.group(key) != value:
                report.add(rel_skill_md, lineno, "reviewed", "the 'Reviewed against' line says %s %s but metadata.%s is %s"
                           % (key, m.group(key), key, value if value is not None else "missing"))
        if month is not None and (m.group("month"), m.group("year")) != month:
            report.add(rel_skill_md, lineno, "reviewed", "the 'Reviewed against' line says (%s %s) but metadata.checked is %s (%s %s)"
                       % (m.group("month"), m.group("year"), checked, month[0], month[1]))
    for lineno, _ in reviewed[1:]:
        report.add(rel_skill_md, lineno, "reviewed", "a second 'Reviewed against' line; keep exactly one, agents compare the live versions with it")
    if not reviewed and (gateway or fabric):
        report.add(rel_skill_md, doc.frontmatter_end + 1, "reviewed",
                   "no '%s' line in the body; agents compare the live versions with it" % REVIEWED_LINE_SHAPE)

    rel_commands = skill + "/" + COMMANDS_MD
    if rel_commands in docs:
        lines = docs[rel_commands].lines
        allowed[rel_commands] = set(range(1, next((i for i, l in enumerate(lines) if l.startswith("## ")), len(lines)) + 1))

    where = "SKILL.md metadata, its 'Reviewed against' line or the generated header of commands.md"
    for rel in files:
        if not rel.startswith(skill + "/"):
            continue
        for lineno, line in enumerate((read_text(os.path.join(root, rel)) or "").split("\n"), start=1):
            if lineno in allowed.get(rel, ()):
                continue
            for kind, literal in literal_matches(patterns, line):
                what = "date %r is in the review month" % literal if kind == "date" else "version literal %r" % literal
                report.add(rel, lineno, "reviewed", "%s; it goes stale at the next review, so write it only in %s, "
                           "and say 'the reviewed version' here" % (what, where))

    for rel in (".claude-plugin/plugin.json", ".claude-plugin/marketplace.json"):
        path = os.path.join(root, rel)
        mtext = read_text(path) if os.path.isfile(path) else None
        try:
            data = json.loads(mtext or "")
        except ValueError:
            continue
        if not isinstance(data, dict):
            continue
        meta, plugins = data.get("metadata"), data.get("plugins")
        descriptions = [data.get("description"), meta.get("description") if isinstance(meta, dict) else None]
        descriptions += [p.get("description") for p in plugins if isinstance(p, dict)] if isinstance(plugins, list) else []
        for desc in descriptions:
            for _, literal in literal_matches(patterns, desc) if isinstance(desc, str) else ():
                report.add(rel, json_line(mtext, desc[:40]), "reviewed",
                           "description names %r, which goes stale at the next review; keep versions in "
                           "SKILL.md's metadata" % literal)


