FENCE_OPEN_RE = re.compile(r"^(\s*)(`{3,}|~{3,})(.*)$")
ATX_RE = re.compile(r"^ {0,3}(#{1,6})(?:[ \t]+(.*?))?(?:[ \t]+#+)?[ \t]*$")
HTML_COMMENT_RE = re.compile(r"<!--[\s\S]*?--!?>")
INLINE_LINK_RE = re.compile(
    r"(!?)\[((?:[^\[\]\\]|\\.|\[[^\[\]]*\])*)\]\(\s*(<[^>\n]*>|[^\s()]*(?:\([^\s()]*\)[^\s()]*)*)"
    r"(?:\s+(?:\"[^\"]*\"|'[^']*'|\([^)]*\)))?\s*\)"
)
FRONTMATTER_LINE_RE = re.compile(r"^( *)([A-Za-z0-9_.-]+):[ \t]*(.*?)[ \t]*$")


class Fence:
    def __init__(self, line, info, lines, closed):
        self.line = line          # line number of the opening fence
        self.lang = info.split()[0].lower() if info.split() else ""
        self.lines = lines        # body lines
        self.closed = closed


class MdDoc:
    """The parts of a Markdown file the checks need: frontmatter, prose lines and fenced blocks."""

    def __init__(self, text):
        self.lines = text.split("\n")
        self.fences = []
        self.prose = []           # (lineno, line) outside fences and frontmatter
        self.fields = self.metadata = None
        self.frontmatter_end = 0  # line number of the closing '---', 0 without frontmatter
        if self.lines and self.lines[0].rstrip() == "---":
            self.fields, self.metadata = {}, {}
            parent = None
            for j in range(1, len(self.lines)):
                if self.lines[j].rstrip() == "---":
                    self.frontmatter_end = j + 1
                    break
                m = FRONTMATTER_LINE_RE.match(self.lines[j])
                if not m:
                    continue
                indent, key, value = m.groups()
                if len(value) >= 2 and value[0] == value[-1] and value[0] in "'\"":
                    value = value[1:-1]
                if not indent:
                    parent = key
                    self.fields[key] = (value, j + 1)
                elif parent == "metadata" and indent == "  ":
                    self.metadata[key] = (value, j + 1)
            if not self.frontmatter_end:
                self.fields = self.metadata = None
        i = self.frontmatter_end
        while i < len(self.lines):
            m = FENCE_OPEN_RE.match(self.lines[i])
            if m and not (m.group(2)[0] == "`" and "`" in m.group(3)):
                close_re = re.compile(r"^\s*" + re.escape(m.group(2)[0]) + "{" + str(len(m.group(2))) + r",}[ \t]*$")
                body, j = [], i + 1
                while j < len(self.lines) and not close_re.match(self.lines[j]):
                    body.append(self.lines[j])
                    j += 1
                self.fences.append(Fence(i + 1, m.group(3), body, j < len(self.lines)))
                i = j + 1
                continue
            self.prose.append((i + 1, self.lines[i]))
            i += 1
        self._anchors = None

    def anchors(self):
        if self._anchors is None:
            seen, self._anchors = {}, set()
            for _, line in self.prose:
                m = ATX_RE.match(line)
                if not m:
                    continue
                slug = github_slug(m.group(2) or "")
                seen[slug] = seen.get(slug, -1) + 1
                self._anchors.add(slug if not seen[slug] else "%s-%d" % (slug, seen[slug]))
        return self._anchors


def github_slug(text):
    """GitHub's heading anchor: rendered text, lowercased, punctuation except '-' and '_' dropped."""
    t = re.sub(r"!?\[([^\]]*)\]\([^)]*\)", r"\1", text)
    t = re.sub(r"<[^>]+>", "", t).replace("`", "")
    t = re.sub(r"\*+|~~", "", t)
    t = re.sub(r"(?<!\w)_+|_+(?!\w)", "", t)
    t = re.sub(r"[^\w\- ]", "", t.strip().lower())
    return t.replace(" ", "-")


def code_spans(line):
    """CommonMark code spans on one line: [(start, end, content)]; unmatched backticks are literal."""
    spans, i, n = [], 0, len(line)
    while i < n:
        if line[i] == "\\" and i + 1 < n and line[i + 1] == "`":
            i += 2
            continue
        if line[i] != "`":
            i += 1
            continue
        j = i
        while j < n and line[j] == "`":
            j += 1
        width, k, close = j - i, j, None
        while k < n:
            if line[k] != "`":
                k += 1
                continue
            m = k
            while m < n and line[m] == "`":
                m += 1
            if m - k == width:
                close = (k, m)
                break
            k = m
        if close is None:
            i = j
            continue
        content = line[j:close[0]]
        if len(content) >= 2 and content[0] == " " and content[-1] == " " and content.strip():
            content = content[1:-1]
        spans.append((i, close[1], content))
        i = close[1]
    return spans


def table_cell_text(line, content):
    """A code span as the reader sees it: in a table row, '\\|' stands for '|' even inside code."""
    return content.replace("\\|", "|") if line.lstrip().startswith("|") else content


def links_in(doc):
    """(lineno, target) for inline links and images outside code spans and HTML comments."""
    out = []
    for lineno, line in doc.prose:
        chars = list(line)
        for start, end, _ in code_spans(line):
            chars[start:end] = " " * (end - start)
        scan = HTML_COMMENT_RE.sub(lambda m: " " * len(m.group(0)), "".join(chars))
        out.extend((lineno, m.group(3)) for m in INLINE_LINK_RE.finditer(scan))
    return out


