def load_snapshot(root, report):
    path = os.path.join(root, CLI_SNAPSHOT)
    if not os.path.isfile(path):
        report.add(CLI_SNAPSHOT, 1, "fabric", "missing; run make cli-reference FABRIC=/path/to/fabric")
        return None
    try:
        tree = json.loads(read_text(path) or "")
        if isinstance(tree, dict) and "root" in tree and "fabric_version" in tree:
            return tree
        raise ValueError("expected an object with 'root' and 'fabric_version'")
    except ValueError as exc:
        report.add(CLI_SNAPSHOT, 1, "fabric", "unreadable (%s); run make cli-reference" % exc)
        return None


def main(argv=None):
    parser = argparse.ArgumentParser(description="Offline checks specific to this skill repository.")
    parser.add_argument("--root", default=DEFAULT_ROOT, help="repository root (default: %(default)s)")
    root = os.path.abspath(parser.parse_args(argv).root)
    report = Report(root)

    files = list_files(root)
    skills = skill_dirs(files)
    if "skills/" + MAIN_SKILL not in skills:
        report.add("skills/" + MAIN_SKILL, 1, "frontmatter", "the skill directory is missing")
    docs = {}
    for rel in files:
        text = read_text(os.path.join(root, rel)) if rel.endswith(".md") else None
        if text is not None:
            docs[rel] = MdDoc(text)

    for skill in skills:
        metadata = check_skill(skill, docs, report)
        check_maintainer_material(skill, docs, report)
        if metadata is not None:
            check_reviewed_literals(root, skill, metadata, files, docs, report)
    for rel in sorted(docs):
        check_links(root, rel, docs[rel], docs, skills, report)
    check_matrix(root, docs, skills, report)
    scanned = check_banned(root, files, known_issue_ids(root, skills), report)

    commands = 0
    tree = load_snapshot(root, report)
    if tree is not None:
        for rel in sorted(docs):
            if rel.startswith(("skills/", "tests/e2e/fixtures/")):
                commands += check_fabric_commands(tree, rel, docs[rel], report)
        check_generated(root, tree, report)

    report.print()
    n = len(set(report.problems))
    if n:
        print("validate: FAILED, %d problem%s (%d files, %d Markdown, %d fabric commands checked)"
              % (n, "" if n == 1 else "s", len(files), len(docs), commands))
        return 1
    print("validate: OK, %d files (%d scanned for banned content), %d Markdown, %d skill(s), %d fabric commands checked"
          % (len(files), scanned, len(docs), len(skills), commands))
    return 0


if __name__ == "__main__":
    sys.exit(main())
