SHELL_LANGS = ("", "bash", "sh", "shell", "console", "zsh")
LEADING_WORDS = ("if", "then", "else", "elif", "do", "while", "until", "!", "time", "command", "exec", "{")
TOKEN_RE = re.compile(r"(?P<word>(?:<[A-Za-z_][\w.:-]*>|\$\{[^}]*\}|\\.|[^\s\"'|;&<>()`\\]|\"(?:[^\"\\]|\\.)*\"|'[^']*')+)"
                      r"|(?P<op>&&|\|\||[|;&<>()`])|\S")
HEREDOC_RE = re.compile(r"(?<!<)<<(?!<)(-?)\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\2")
ASSIGNMENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*=")


def shell_lines(fence):
    """(lineno, line) for each command line of a shell block: continuations joined, heredoc bodies
    and console output skipped, '$ ' prompts removed."""
    out, buf, start, heredoc = [], None, 0, None
    for idx, raw in enumerate(fence.lines):
        line = raw.strip()
        if heredoc:
            heredoc = None if line == heredoc else heredoc
            continue
        if buf is None:
            if fence.lang == "console":
                if not line.startswith("$"):
                    continue
                line = line[1:].lstrip()
            elif line.startswith("$ "):
                line = line[2:]
            if not line:
                continue
            buf, start = line, fence.line + 1 + idx
        else:
            buf += " " + line
        if buf.endswith("\\"):
            buf = buf[:-1]
            continue
        out.append((start, buf))
        m = HEREDOC_RE.search(buf)
        heredoc, buf = (m.group(3) if m else None), None
    return out + ([(start, buf)] if buf is not None else [])


def split_substitutions(text):
    """(text, bodies): each $(...) outside single quotes replaced by $_, and the bodies it held."""
    out, bodies, i, quote = [], [], 0, None
    while i < len(text):
        if text[i] == "\\" and quote != "'":
            out.append(text[i:i + 2])
            i += 2
            continue
        if quote != "'" and text.startswith("$(", i) and not text.startswith("$((", i):
            depth, j = 1, i + 2
            while j < len(text) and depth:
                depth += {"(": 1, ")": -1}.get(text[j], 0)
                j += 1
            bodies.append(text[i + 2:j - 1 if depth == 0 else j])
            out.append("$_")
            i = j
            continue
        if text[i] in "'\"" and quote in (None, text[i]):
            quote = None if quote else text[i]
        out.append(text[i])
        i += 1
    return "".join(out), bodies


def fabric_invocations(text):
    """The words of each `fabric` command on one shell line, `fabric` first, quotes removed."""
    text, bodies = split_substitutions(text)
    out = [words for body in bodies for words in fabric_invocations(body)]
    tokens = []
    for m in TOKEN_RE.finditer(text):
        if m.lastgroup != "op" and m.group(0).startswith("#"):
            break
        tokens.append((m.lastgroup == "op", m.group(0), m.start(), m.end()))
    for i, (is_op, word, _, _) in enumerate(tokens):
        prev = tokens[i - 1] if i else None
        if word != "fabric" or is_op or not (prev is None or prev[0] or prev[1] in LEADING_WORDS
                                             or ASSIGNMENT_RE.match(prev[1])):
            continue
        words = ["fabric"]
        for j in range(i + 1, len(tokens)):
            if tokens[j][0]:
                break
            nxt = tokens[j + 1] if j + 1 < len(tokens) else None
            if nxt and nxt[1] in "<>" and nxt[2] == tokens[j][3] and tokens[j][1].isdigit():
                break
            word = tokens[j][1].replace('"', "").replace("'", "")
            if word:
                words.append(word)
        out.append(words)
    return out


def is_placeholder(tok):
    return "<" in tok or ">" in tok or "..." in tok or tok.startswith(("[", "{", "$"))


def option_lookup(node, name):
    for opt in node.get("options", []):
        if name.startswith("--") and opt.get("long") == name[2:]:
            return opt
        if not name.startswith("--") and opt.get("short") == name[1:]:
            return opt
        if any(name.lstrip("-") == alias.lstrip("-") for alias in opt.get("aliases", [])):
            return opt
    return None


def option_names(node):
    names = []
    for opt in node.get("options", []):
        names += (["--" + opt["long"]] if "long" in opt else []) + (["-" + opt["short"]] if "short" in opt else [])
    return names


def suggestion(word, candidates):
    close = difflib.get_close_matches(word, candidates, n=3, cutoff=0.5)
    if close:
        return "; did you mean: " + ", ".join(close) + "?"
    return "; valid: " + ", ".join(candidates[:10]) + (", ..." if len(candidates) > 10 else "")


def check_fabric_tokens(tree, tokens, report, rel, lineno, complete_required):
    root = tree["root"]
    global_longs = set(tree.get("global_options", []))
    node, path = root, ["fabric"]
    i, positional = 1, False
    while i < len(tokens):
        tok = tokens[i]
        if tok == "--":
            return
        if tok.startswith("-") and tok != "-" and not re.match(r"^-\d+(\.\d+)?$", tok) and not is_placeholder(tok.split("=", 1)[0]):
            if tok.startswith("--"):
                name, _, attached = tok.partition("=")
                attached = attached if "=" in tok else None
            else:
                name, attached = tok[:2], (tok[2:].lstrip("=") or None)
            if name in ("--help", "-h"):
                i += 1
                continue
            opt = option_lookup(node, name)
            if opt is None:
                gopt = option_lookup(root, name)
                if gopt is not None and gopt.get("long") in global_longs:
                    opt = gopt
            if opt is None:
                hint = suggestion(name, option_names(node))
                group = next((c for c in root.get("commands", []) if option_lookup(c, name)), None)
                if node is root and group is not None:
                    hint = "; it goes after the appliance group: `fabric %s %s`" % (group["name"], name)
                report.add(rel, lineno, "fabric", "`%s` has no option %s%s" % (" ".join(path), name, hint))
                i += 1
                continue
            value = opt.get("value", "")
            if value and attached is None:
                if value.startswith("["):
                    if i + 1 < len(tokens) and not tokens[i + 1].startswith("-"):
                        i += 1
                else:
                    count = max(1, value.count("<"))
                    if i + count >= len(tokens):
                        report.add(rel, lineno, "fabric", "`%s %s` needs a value" % (" ".join(path), name))
                    i += count
            i += 1
            continue
        if node.get("commands") and not positional:
            if is_placeholder(tok) or tok == "help":
                return
            child = next((c for c in node["commands"] if c["name"] == tok or tok in c.get("aliases", [])), None)
            if child is not None:
                node = child
                path.append(tok)
                i += 1
                continue
            if not node.get("arguments"):
                hint = suggestion(tok, [c["name"] for c in node["commands"]])
                group = next((c for c in root["commands"] if any(g["name"] == tok for g in c.get("commands", []))), None)
                if node is root and group is not None:
                    hint = "; it is under the appliance group: `fabric %s %s`" % (group["name"], tok)
                report.add(rel, lineno, "fabric", "`%s` has no subcommand %r%s" % (" ".join(path), tok, hint))
                return
        positional = True
        i += 1
    if complete_required and node.get("commands") and "<COMMAND>" in node.get("usage", ""):
        if not set(tokens) & {"--help", "-h", "--version", "-V"}:
            report.add(rel, lineno, "fabric", "`%s` needs a subcommand (%s)"
                       % (" ".join(path), ", ".join(c["name"] for c in node["commands"][:8])))


def check_fabric_commands(tree, rel, doc, report):
    count = 0
    for fence in doc.fences:
        if fence.lang in SHELL_LANGS:
            for lineno, line in shell_lines(fence):
                for words in fabric_invocations(line):
                    check_fabric_tokens(tree, words, report, rel, lineno, True)
                    count += 1
    for lineno, line in doc.prose:
        for _, _, content in code_spans(line):
            content = table_cell_text(line, content)
            if content == "fabric" or content.startswith("fabric "):
                for words in fabric_invocations(content):
                    check_fabric_tokens(tree, words, report, rel, lineno, False)
                    count += 1
    return count


